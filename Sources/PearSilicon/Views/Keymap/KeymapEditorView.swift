import SwiftUI

/// Editor for a single app's keymap.
struct KeymapEditorView: View {
    @EnvironmentObject private var state: AppState
    let app: InstalledApp

    @State private var draft: Keymap = .empty(bundleID: "")
    @State private var hasLoaded = false
    @Namespace private var glassNamespace

    var body: some View {
        VStack(spacing: 16) {
            toolbar
            enableToggle

            HStack(alignment: .top, spacing: 16) {
                KeymapCanvasView(keymap: $draft)
                    .frame(minWidth: 320, minHeight: 260)
                    .glassEffect(.regular, in: RoundedRectangle(cornerRadius: 18, style: .continuous))

                bindingList
                    .frame(width: 340)
            }
        }
        .task(id: app.id) { load() }
    }

    // MARK: - Enable toggle

    /// Input translation is opt-in and default OFF. Toggling takes effect on the
    /// next launch (the decision is made when the game process starts).
    private var enableToggle: some View {
        let enabled = state.isKeymapperEnabled(for: app)
        let running = state.isRunning(app)
        return HStack(spacing: 10) {
            Toggle("Enable keymapper", isOn: Binding(
                get: { enabled },
                set: { state.setKeymapperEnabled($0, for: app) }
            ))
            .toggleStyle(.switch)

            Text(enabled ? "On" : "Off — the game runs with no input translation")
                .font(.caption)
                .foregroundStyle(.secondary)

            Spacer()

            if running && enabled {
                Button {
                    Task { await state.launch(app) }
                } label: {
                    Label("Relaunch to apply", systemImage: "arrow.clockwise")
                }
                .buttonStyle(.glass)
                .controlSize(.small)
            }
        }
        .padding(.horizontal, 14)
        .padding(.vertical, 10)
        .glassEffect(.regular, in: RoundedRectangle(cornerRadius: 14, style: .continuous))
    }

    // MARK: - Toolbar

    private var toolbar: some View {
        HStack(spacing: 12) {
            Text(L10n.keymap)
                .font(.title3.weight(.semibold))
            Spacer()

            if draft.isAutoGenerated {
                Text("Auto-generated")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            }

            Button {
                state.generateKeymap(for: app)
                load()
            } label: {
                Label(L10n.generateKeymap, systemImage: "wand.and.stars")
            }
            .buttonStyle(.glass)

            Button {
                draft = KeymapGenerator.generate(for: app)
            } label: {
                Label(L10n.resetKeymap, systemImage: "arrow.counterclockwise")
            }
            .buttonStyle(.glass)

            Button {
                state.openOverlay(for: app)
            } label: {
                Label("Overlay", systemImage: "rectangle.on.rectangle")
            }
            .buttonStyle(.glass)

            Button {
                draft.isAutoGenerated = false
                state.saveKeymap(draft)
            } label: {
                Label("Save", systemImage: "square.and.arrow.down")
            }
            .buttonStyle(.glassProminent)
        }
    }

    // MARK: - Binding list

    private var bindingList: some View {
        VStack(alignment: .leading, spacing: 8) {
            HStack {
                SectionTitle(text: "Bindings")
                Spacer()
                Button {
                    draft.isAutoGenerated = false
                    draft.bindings.append(
                        KeymapBinding(key: "x", action: .tap(NormalizedPoint(0.5, 0.5)))
                    )
                } label: {
                    Image(systemName: "plus")
                }
                .buttonStyle(.glass)
                .controlSize(.small)
            }

            if draft.bindings.isEmpty {
                Text(L10n.noKeymap)
                    .font(.callout)
                    .foregroundStyle(.secondary)
                    .padding(.vertical, 8)
            } else {
                ScrollView {
                    VStack(spacing: 6) {
                        ForEach($draft.bindings) { $binding in
                            BindingRow(binding: $binding) {
                                draft.isAutoGenerated = false
                                draft.bindings.removeAll { $0.id == binding.id }
                            }
                        }
                    }
                }
            }
        }
        .padding(14)
        .glassEffect(.regular, in: RoundedRectangle(cornerRadius: 18, style: .continuous))
    }

    // MARK: - Loading

    private func load() {
        if let stored = try? state.keymapStore.load(for: app.id) {
            draft = stored
        } else {
            draft = KeymapGenerator.generate(for: app)
        }
        state.currentKeymap = draft
    }
}

/// A single editable binding row.
private struct BindingRow: View {
    @Binding var binding: KeymapBinding
    let onDelete: () -> Void

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack(spacing: 8) {
                TextField("Key", text: $binding.key)
                    .textFieldStyle(.plain)
                    .frame(width: 64)
                    .padding(.horizontal, 8)
                    .padding(.vertical, 5)
                    .glassEffect(.regular, in: RoundedRectangle(cornerRadius: 8, style: .continuous))

                Text(binding.actionKind)
                    .font(.callout)
                    .foregroundStyle(.secondary)

                Spacer()

                Button {
                    onDelete()
                } label: {
                    Image(systemName: "trash")
                }
                .buttonStyle(.plain)
                .foregroundStyle(.secondary)
            }

            if let radius = joystickRadius {
                HStack(spacing: 8) {
                    Text("Stick radius")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                        .frame(width: 74, alignment: .leading)
                    Slider(value: radius, in: 0.02...0.30)
                    Text("\(Int(radius.wrappedValue * 100))%")
                        .font(.caption.monospacedDigit())
                        .foregroundStyle(.secondary)
                        .frame(width: 38, alignment: .trailing)
                }
            }
        }
    }

    /// Nil for non-joystick bindings. Touch-down happens at the centre, then the
    /// finger drags to `centre + direction * radius`.
    private var joystickRadius: Binding<Double>? {
        guard case .joystick(let center, let radius) = binding.action else { return nil }
        return Binding(
            get: { radius },
            set: { binding.action = .joystick(center: center, radius: $0) }
        )
    }
}
