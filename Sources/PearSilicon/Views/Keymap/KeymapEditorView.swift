import SwiftUI

/// Editor for a single app's keymap.
struct KeymapEditorView: View {
    @EnvironmentObject private var state: AppState
    let app: InstalledApp

    @State private var draft: Keymap = .empty(bundleID: "")
    @State private var hasLoaded = false
    @State private var confirmDeleteAll = false
    @Namespace private var glassNamespace

    var body: some View {
        VStack(spacing: 16) {
            toolbar
            enableToggle

            HStack(alignment: .top, spacing: 16) {
                KeymapCanvasView(keymap: $draft)
                    .frame(minWidth: 320, minHeight: 260)
                    .glassEffect(.regular, in: RoundedRectangle(cornerRadius: 18, style: .continuous))

                bindingList
                    .frame(width: 340)
            }
        }
        .task(id: app.id) { load() }
    }

    // MARK: - Enable toggle

    /// Input translation is opt-in and default OFF. Toggling takes effect on the
    /// next launch (the decision is made when the game process starts).
    private var enableToggle: some View {
        let enabled = state.isKeymapperEnabled(for: app)
        let running = state.isRunning(app)
        return HStack(spacing: 10) {
            Toggle("Enable keymapper", isOn: Binding(
                get: { enabled },
                set: { state.setKeymapperEnabled($0, for: app) }
            ))
            .toggleStyle(.switch)

            Text(enabled ? "On" : "Off — the game runs with no input translation")
                .font(.caption)
                .foregroundStyle(.secondary)

            Spacer()

            if running && enabled {
                Button {
                    Task { await state.launch(app) }
                } label: {
                    Label("Relaunch to apply", systemImage: "arrow.clockwise")
                }
                .buttonStyle(.glass)
                .controlSize(.small)
            }
        }
        .padding(.horizontal, 14)
        .padding(.vertical, 10)
        .glassEffect(.regular, in: RoundedRectangle(cornerRadius: 14, style: .continuous))
    }

    // MARK: - Toolbar

    private var toolbar: some View {
        HStack(spacing: 12) {
            Text(L10n.keymap)
                .font(.title3.weight(.semibold))
            Spacer()

            if draft.isAutoGenerated {
                Text("Auto-generated")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            }

            Button {
                state.generateKeymap(for: app)
                load()
            } label: {
                Label(L10n.generateKeymap, systemImage: "wand.and.stars")
            }
            .buttonStyle(.glass)

            Button {
                draft = KeymapGenerator.generate(for: app)
            } label: {
                Label(L10n.resetKeymap, systemImage: "arrow.counterclockwise")
            }
            .buttonStyle(.glass)

            Button {
                state.openOverlay(for: app)
            } label: {
                Label("Overlay", systemImage: "rectangle.on.rectangle")
            }
            .buttonStyle(.glass)

            Button(role: .destructive) {
                confirmDeleteAll = true
            } label: {
                Label("Delete All", systemImage: "trash")
            }
            .buttonStyle(.glass)
            .disabled(draft.bindings.isEmpty)

            Button {
                draft.isAutoGenerated = false
                state.saveKeymap(draft)
            } label: {
                Label("Save", systemImage: "square.and.arrow.down")
            }
            .buttonStyle(.glassProminent)
        }
        .alert("Delete all bindings?", isPresented: $confirmDeleteAll) {
            Button("Delete All", role: .destructive) {
                draft.isAutoGenerated = false
                draft.bindings.removeAll()
            }
            Button("Cancel", role: .cancel) {}
        } message: {
            Text("This removes every key mapping for this app. You can generate a template again afterwards.")
        }
    }

    // MARK: - Binding list

    private var bindingList: some View {
        VStack(alignment: .leading, spacing: 8) {
            HStack {
                SectionTitle(text: "Bindings")
                Spacer()
                Menu {
                    ForEach(KeymapActionKind.allCases) { kind in
                        Button {
                            addBinding(kind)
                        } label: {
                            Label(kind.displayName, systemImage: kind.systemImage)
                        }
                    }
                } label: {
                    Image(systemName: "plus")
                }
                .menuStyle(.borderlessButton)
                .fixedSize()
                .help("Add a tap, hold, joystick, mouse-look or swipe binding")
            }

            if draft.bindings.isEmpty {
                Text(L10n.noKeymap)
                    .font(.callout)
                    .foregroundStyle(.secondary)
                    .padding(.vertical, 8)
            } else {
                ScrollView {
                    VStack(spacing: 6) {
                        ForEach($draft.bindings) { $binding in
                            BindingRow(binding: $binding) {
                                draft.isAutoGenerated = false
                                draft.bindings.removeAll { $0.id == binding.id }
                            }
                        }
                    }
                }
            }
        }
        .padding(14)
        .glassEffect(.regular, in: RoundedRectangle(cornerRadius: 18, style: .continuous))
    }

    private func addBinding(_ kind: KeymapActionKind) {
        draft.isAutoGenerated = false
        let binding: KeymapBinding
        switch kind {
        case .joystick:
            binding = KeymapBinding(key: "wasd", action: .make(kind))
        case .mouseLook:
            binding = KeymapBinding(key: "mouse", action: .make(kind))
        default:
            binding = KeymapBinding(key: "x", action: .make(kind))
        }
        draft.bindings.append(binding)
    }

    // MARK: - Loading

    private func load() {
        if let stored = try? state.keymapStore.load(for: app.id) {
            draft = stored
        } else {
            draft = KeymapGenerator.generate(for: app)
        }
        state.currentKeymap = draft
    }
}

/// A single editable binding row.
private struct BindingRow: View {
    @Binding var binding: KeymapBinding
    let onDelete: () -> Void

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack(spacing: 8) {
                KeyCaptureField(key: $binding.key)

                Picker("Action", selection: actionKind) {
                    ForEach(KeymapActionKind.allCases) { kind in
                        Text(kind.displayName).tag(kind)
                    }
                }
                .labelsHidden()
                .frame(width: 118)

                Spacer()

                Button {
                    onDelete()
                } label: {
                    Image(systemName: "trash")
                }
                .buttonStyle(.plain)
                .foregroundStyle(.secondary)
            }

            if let radius = joystickRadius {
                HStack(spacing: 8) {
                    Text("Stick radius")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                        .frame(width: 74, alignment: .leading)
                    Slider(value: radius, in: 0.02...0.30)
                    Text("\(Int(radius.wrappedValue * 100))%")
                        .font(.caption.monospacedDigit())
                        .foregroundStyle(.secondary)
                        .frame(width: 38, alignment: .trailing)
                }
            }

            if binding.action.kind == .mouseLook, case .mouseLook(let region, let sensitivity) = binding.action {
                HStack(spacing: 8) {
                    Text("Sensitivity")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                        .frame(width: 74, alignment: .leading)
                    Slider(value: Binding(
                        get: { sensitivity },
                        set: { binding.action = .mouseLook(region: region, sensitivity: $0) }
                    ), in: 0.2...3.0)
                    Text(String(format: "%.1f×", sensitivity))
                        .font(.caption.monospacedDigit())
                        .foregroundStyle(.secondary)
                        .frame(width: 38, alignment: .trailing)
                }
            }
        }
    }

    /// Changing the action keeps its marker and selects the input name the
    /// runtime expects for joystick/mouse-look gestures.
    private var actionKind: Binding<KeymapActionKind> {
        Binding(
            get: { binding.action.kind },
            set: { newKind in
                binding.action = binding.action.converted(to: newKind)
                switch newKind {
                case .joystick:
                    binding.key = "wasd"
                case .mouseLook:
                    binding.key = "mouse"
                default:
                    if binding.key == "wasd" || binding.key == "mouse" {
                        binding.key = "x"
                    }
                }
            }
        )
    }

    /// Nil for non-joystick bindings. Touch-down happens at the centre, then the
    /// finger drags to `centre + direction * radius`.
    private var joystickRadius: Binding<Double>? {
        guard case .joystick(let center, let radius) = binding.action else { return nil }
        return Binding(
            get: { radius },
            set: { binding.action = .joystick(center: center, radius: $0) }
        )
    }
}
