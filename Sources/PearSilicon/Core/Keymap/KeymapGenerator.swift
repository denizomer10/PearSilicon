import Foundation

/// Best-effort engine detection based on the app bundle contents.
enum GameEngine: String, Sendable {
    case unity, unreal, native, unknown

    var displayName: String {
        switch self {
        case .unity: return "Unity"
        case .unreal: return "Unreal Engine"
        case .native: return "Native"
        case .unknown: return "Unknown"
        }
    }
}

/// Produces a sensible starting keymap for an app.
///
/// NOTE: This is a heuristic template, not true automatic control detection.
/// Real control detection would require analyzing rendered frames of the game,
/// which is out of scope. Templates are chosen by engine and can be edited
/// afterwards in the Keymap tab.
enum KeymapGenerator {

    static func detectEngine(bundleURL: URL) -> GameEngine {
        let fileManager = FileManager.default
        let frameworks = bundleURL.appendingPathComponent("Frameworks")

        if fileManager.fileExists(
            atPath: frameworks.appendingPathComponent("UnityFramework.framework").path
        ) {
            return .unity
        }

        if let items = try? fileManager.contentsOfDirectory(atPath: frameworks.path) {
            if items.contains(where: { $0.localizedCaseInsensitiveContains("unity") }) {
                return .unity
            }
            if items.contains(where: {
                let lower = $0.lowercased()
                return lower.contains("ue4") || lower.contains("ue5")
                    || lower.contains("unreal") || lower.contains("epicgames")
            }) {
                return .unreal
            }
        }
        return .unknown
    }

    static func generate(for app: InstalledApp) -> Keymap {
        let engine = detectEngine(bundleURL: app.bundleURL)
        return Keymap(
            bundleID: app.id,
            engine: engine.rawValue,
            isAutoGenerated: true,
            createdAt: Date(),
            bindings: template(for: engine)
        )
    }

    private static func template(for engine: GameEngine) -> [KeymapBinding] {
        // A generic third-person action layout.
        [
            // Movement joystick (driven by W/A/S/D).
            KeymapBinding(key: "wasd",
                          action: .joystick(center: NormalizedPoint(0.14, 0.72), radius: 0.10)),
            // Camera look (passive mouse movement).
            KeymapBinding(key: "mouse",
                          action: .mouseLook(region: NormalizedRect(x: 0.20, y: 0.10, width: 0.60, height: 0.80),
                                             sensitivity: 1.0)),
            KeymapBinding(key: "space", action: .tap(NormalizedPoint(0.90, 0.82))), // Jump
            KeymapBinding(key: "shift", action: .hold(NormalizedPoint(0.85, 0.90))), // Sprint
            KeymapBinding(key: "f", action: .tap(NormalizedPoint(0.80, 0.70))),     // Interact
            KeymapBinding(key: "e", action: .tap(NormalizedPoint(0.86, 0.62))),     // Skill 1
            KeymapBinding(key: "q", action: .tap(NormalizedPoint(0.92, 0.62))),     // Skill 2
            KeymapBinding(key: "1", action: .tap(NormalizedPoint(0.88, 0.50))),     // Slot 1
            KeymapBinding(key: "2", action: .tap(NormalizedPoint(0.94, 0.50))),     // Slot 2
            KeymapBinding(key: "tab", action: .tap(NormalizedPoint(0.50, 0.06))),   // Menu
            KeymapBinding(key: "escape", action: .tap(NormalizedPoint(0.03, 0.05))) // Back
        ]
    }
}
