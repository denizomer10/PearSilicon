import Foundation
import XCTest
@testable import PearSilicon

final class KeymapControllerTests: XCTestCase {
    func testGeneratedPresetStaysOnDiskButManualEditorStartsEmpty() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let store = KeymapStore(baseURL: root)
        var map = Keymap.empty(bundleID: "com.example.manual")
        map.bindings = [KeymapBinding(key: "space", action: .tap(NormalizedPoint(0.5, 0.5)))]
        map.isAutoGenerated = true
        try store.save(map)
        XCTAssertNil(try store.loadManual(for: map.bundleID))
        XCTAssertEqual(try store.load(for: map.bundleID)?.bindings, map.bindings)
        map.isAutoGenerated = false
        try store.save(map)
        XCTAssertEqual(try store.loadManual(for: map.bundleID)?.bindings, map.bindings)
    }

    func testResetClearsBothInputSourcesAndSavesAnEmptyManualLayout() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let store = KeymapStore(baseURL: root)
        var map = Keymap.empty(bundleID: "com.example.reset")
        map.bindings = [
            KeymapBinding(key: "space", action: .make(.tap)),
            KeymapBinding(key: ControllerKey.buttonA.rawValue, source: .controller, action: .make(.tap))
        ]
        try store.save(map)

        map.resetBindings()

        XCTAssertTrue(map.bindings.isEmpty)
        XCTAssertEqual(try store.loadManual(for: map.bundleID)?.bindings.count, 2)
        try store.save(map)
        let saved = try XCTUnwrap(store.loadManual(for: map.bundleID))
        XCTAssertTrue(saved.bindings.isEmpty)
    }

    @MainActor
    func testOverlayContentTracksWindowPositionAndFullScreenOnUpperDisplay() {
        let primary = CGRect(x: 0, y: 0, width: 1440, height: 900)
        let upper = CGRect(x: 0, y: 900, width: 1920, height: 1080)
        let bounds = CGRect(x: 180, y: -760, width: 800, height: 500)
        let start = GameKeymapperOverlay.contentRect(for: bounds, screens: [primary, upper])
        XCTAssertEqual(start.minY, 1160)
        XCTAssertLessThan(start.height, bounds.height)
        let moved = GameKeymapperOverlay.contentRect(for: bounds.offsetBy(dx: 80, dy: 40), screens: [primary, upper])
        XCTAssertEqual(start.offsetBy(dx: 80, dy: -40), moved)
        XCTAssertEqual(
            GameKeymapperOverlay.contentRect(for: CGRect(x: 0, y: -1080, width: 1920, height: 1080), screens: [primary, upper]),
            upper
        )
    }

    func testLegacyBindingsWithoutSourceDecodeAsKeyboard() throws {
        var keymap = Keymap.empty(bundleID: "com.example.legacy")
        keymap.bindings = [
            KeymapBinding(key: "space", action: .tap(NormalizedPoint(0.5, 0.5))),
        ]
        let encoded = try KeymapCoding.encoder.encode(keymap)
        var object = try XCTUnwrap(
            JSONSerialization.jsonObject(with: encoded) as? [String: Any]
        )
        var bindings = try XCTUnwrap(object["bindings"] as? [[String: Any]])
        bindings[0].removeValue(forKey: "source")
        object["bindings"] = bindings
        let legacy = try JSONSerialization.data(withJSONObject: object)
        let decoded = try KeymapCoding.decoder.decode(Keymap.self, from: legacy)
        XCTAssertEqual(decoded.bindings.first?.source, .keyboard)
        XCTAssertEqual(decoded.bindings.first?.displayKey, "SPACE")
    }

    func testControllerRecordingIgnoresInputsHeldBeforeRecording() {
        var tracker = ControllerPressTracker(held: [.leftTrigger])
        XCTAssertNil(tracker.nextKey(in: [.leftTrigger], for: .tap))
        XCTAssertEqual(tracker.nextKey(in: [.leftTrigger, .buttonB], for: .tap), .buttonB)
        XCTAssertNil(tracker.nextKey(in: [], for: .tap))
        XCTAssertEqual(tracker.nextKey(in: [.leftTrigger], for: .tap), .leftTrigger)
    }

    func testControllerRecordingAcceptsMovementOnlyForStickActions() {
        var tracker = ControllerPressTracker()
        XCTAssertNil(tracker.nextKey(in: [.buttonA], for: .joystick))
        XCTAssertEqual(tracker.nextKey(in: [.buttonA, .rightStick], for: .joystick), .rightStick)
        XCTAssertNil(tracker.nextKey(in: [.leftStick], for: .hold))
        XCTAssertEqual(tracker.nextKey(in: [.leftStick, .dpadDown], for: .swipe), .dpadDown)
    }

    func testControllerBindingsRoundTripAndDisplayNames() throws {
        var keymap = Keymap.empty(bundleID: "com.example.game")
        keymap.bindings = [
            KeymapBinding(key: ControllerKey.buttonA.rawValue, source: .controller,
                          action: .tap(NormalizedPoint(0.9, 0.8))),
            KeymapBinding(key: ControllerKey.leftStick.rawValue, source: .controller,
                          action: .joystick(center: NormalizedPoint(0.15, 0.75), radius: 0.1)),
            KeymapBinding(key: ControllerKey.rightStick.rawValue, source: .controller,
                          action: .mouseLook(region: .full, sensitivity: 1.4)),
        ]
        let data = try KeymapCoding.encoder.encode(keymap)
        let decoded = try KeymapCoding.decoder.decode(Keymap.self, from: data)
        XCTAssertEqual(decoded.bindings.map(\.source), [.controller, .controller, .controller])
        XCTAssertEqual(decoded.bindings.map(\.displayKey), ["A", "L STICK", "R STICK"])
        XCTAssertTrue(decoded.bindings[1].usesReservedInput)
        XCTAssertTrue(decoded.bindings[2].usesReservedInput)
        XCTAssertEqual(decoded.bindings[2].action, keymap.bindings[2].action)
    }
}
